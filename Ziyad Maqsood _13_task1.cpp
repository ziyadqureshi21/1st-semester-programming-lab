#include <iostream>
using namespace std;

int main() {
    int remainder = 10 % 4;
    float average = (10 + 4) / 2.0;
    int square1 = 10 * 10;
    int square2 = 4 * 4;

    cout << "Remainder = " << remainder << endl;
    cout << "Average = " << average << endl;
    cout << "Square of first number (10) = " << square1 << endl;
    cout << "Square of second number (4) = " << square2 << endl;

    return 0;
}
